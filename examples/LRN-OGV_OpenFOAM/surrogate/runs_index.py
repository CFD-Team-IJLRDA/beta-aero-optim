"""
Writes runs/RUNS.md: one row per kept run (INR and GP) with its purpose, data, key settings and key metrics.
Purposes live in PURPOSE below (edit when adding or deleting runs); metrics come from each run's files.

Usage: ~/miniconda3/envs/ipynb/bin/python runs_index.py
"""
import json
import os
import sys

import numpy as np
import pandas as pd

import _repo  # noqa: E402,F401  (repository on sys.path; SRC, WORK)
HERE = _repo.WORK                 # data, runs, sopt: the surrogate work folder (aero_optim/surrogate/paths.py)
RUNS = os.path.join(HERE, "runs")
PURPOSE = {
    "mean_s1": "seed study: paper config on time-averaged fields, apex FusedLAMB, 1 GPU + CUDA graphs, seed 1",
    "mean_s2": "seed study: seed 2",
    "mean_noclip_s0": "seed study: FusedLAMB without gradient clipping, seed 0",
    "mean_noclip_s1": "seed study: FusedLAMB without gradient clipping, seed 1",
    "base_s0": "batch ideas_9oct, baseline arm (paper config, new code: val QoI metric), seed 0",
    "per_s0": "batch ideas_9oct, periodic embedding, seed 0", "per_s1": "batch ideas_9oct, periodic embedding, seed 1",
    "per_s2": "batch ideas_9oct, periodic embedding, seed 2",
    "aug_s0": "batch ideas_9oct, MP-line points, seed 0", "aug_s1": "batch ideas_9oct, MP-line points, seed 1",
    "aug_s2": "batch ideas_9oct, MP-line points, seed 2",
    "peraug_s0": "batch ideas_9oct, periodic + MP-line points, seed 0", "peraug_s1": "batch ideas_9oct, periodic + MP-line points, seed 1",
    "peraug_s2": "batch ideas_9oct, periodic + MP-line points, seed 2",
    "hpo": "Jean Zay campaigns (pilot/, screening/, optuna_1/ ...): trials/, jobs/, results.csv; see hpo/README.md and RESULTS.md",
    "gp_mean": "GP baseline on the time-averaged QoIs (data_mean/), same window as the mean fields",
}


def qoi_row(path, kind):
    d = pd.read_csv(path)
    out = {}
    for op in ("ADP", "OP1", "OP2"):
        s = d[d.op == op]
        out[f"loss rel. MAE {op}"] = f"{100 * np.mean(np.abs(s.w_pred - s.w_avg) / s.w_avg):.1f} %"
    out["angle MAE"] = f"{np.mean(np.abs(d.phi_pred - d.phi_avg)):.3f}°"
    if kind == "inr":
        out["field NRMSE p (test)"] = f"{100 * d.nrmse_p.mean():.2f} %"
    return out


def main():
    rows = []
    for name in sorted(os.listdir(RUNS)):
        run = os.path.join(RUNS, name)
        if not os.path.isdir(run):
            continue
        row = {"run": name, "purpose": PURPOSE.get(name, "**undocumented**")}
        if os.path.isfile(os.path.join(run, "config.json")):
            c = json.load(open(os.path.join(run, "config.json")))
            row["data"] = c.get("data", "data")
            row["settings"] = (f"{c['hidden']}x{c['layers']}, ω {c['omega']}, lr {c['lr']}, batch {c['batch']}, "
                               f"{c['epochs']} ep, seed {c['seed']}, {c.get('gpus', 1)} GPU")
            if os.path.isfile(os.path.join(run, "summary.json")):
                s = json.load(open(os.path.join(run, "summary.json")))
                row["best epoch"] = s["best_epoch"]
                row["val MSE"] = f"{s['best_val_mse']:.2e}"
                row["train time"] = f"{s['train_wall_s'] / 60:.0f} min"
            if os.path.isfile(os.path.join(run, "eval_test.csv")):
                row.update(qoi_row(os.path.join(run, "eval_test.csv"), "inr"))
        elif os.path.isfile(os.path.join(run, "gp_eval_test.csv")):
            row["data"] = "data_mean" if "mean" in name else "data"
            row["settings"] = "Matern 5/2 ARD, 10 restarts, 1 GP per OP and QoI"
            row.update(qoi_row(os.path.join(run, "gp_eval_test.csv"), "gp"))
        rows.append(row)
    df = pd.DataFrame(rows).fillna("")
    cols = list(df.columns)
    lines = ["# Runs index (generated by `runs_index.py`; QoI metrics on the 88 test blades vs CFD time-averaged QoIs)", "",
             "| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    lines += ["| " + " | ".join(str(v) for v in r) + " |" for r in df.itertuples(index=False)]
    lines += ["", "Comparison files: `compare_<inr>_vs_<gp>.md` (all metrics, per set). Seed/ensemble notes: `../hpo/README.md`."]
    open(os.path.join(RUNS, "RUNS.md"), "w").write("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
